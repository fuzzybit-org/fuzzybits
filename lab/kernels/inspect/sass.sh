#!/usr/bin/env bash
# Usage (inside the lab container, after a run filled the AdaptiveCpp JIT cache): sass.sh ARCH [jit-cache-dir]
# For each cached PTX module: kernel name, registers/spills (ptxas -v), SASS opcode histogram.
set -euo pipefail
arch="${1:-sm_70}"
dir="${2:-$(ls -d /root/.acpp/apps/*/jit-cache | head -1)}"
out=/lab/sass; mkdir -p "${out}"
for f in "${dir}"/*.jit; do
  head -c 40 "$f" | grep -q "Generated by LLVM NVPTX" || continue
  b=$(basename "$f" .jit)
  cp "$f" "${out}/${b}.ptx"
  # PTX may target a different sm; force ours.
  sed -i -E "s/^\.target sm_[0-9]+/.target ${arch}/" "${out}/${b}.ptx"
  name=$(grep -m1 -oE '\.globl\s+\S+' "${out}/${b}.ptx" | awk '{print $2}')
  dn=$(echo "$name" | c++filt | grep -oE 'integral_constant<[^>]*>|\$_[0-9]+' | tr '\n' ' ')
  info=$(/usr/local/cuda/bin/ptxas -arch="${arch}" -O3 -v "${out}/${b}.ptx" -o "${out}/${b}.cubin" 2>&1 | grep -E "registers|spill" | tr -s ' ' | tr '\n' ' ')
  /usr/local/cuda/bin/cuobjdump -sass "${out}/${b}.cubin" > "${out}/${b}.sass"
  total=$(grep -cE '^\s+/\*[0-9a-f]{4}\*/' "${out}/${b}.sass" || true)
  hist=$(grep -oE '^\s+/\*[0-9a-f]{4}\*/\s+(@!?U?P[0-9T] )?[A-Z0-9_.]+' "${out}/${b}.sass" | awk '{print $NF}' | sed -E 's/\..*//' | sort | uniq -c | sort -rn | head -14 | awk '{printf "%s:%s ", $2, $1}')
  echo "== ${b} [${dn}] static_instrs=${total}"
  echo "   ${info}"
  echo "   ${hist}"
done
